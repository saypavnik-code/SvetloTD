// ─────────────────────────────────────────────────────────────────────────────
// BootScene.ts  —  First scene. Sets up global Phaser config, then hands off
//                  to MenuScene immediately.
// ─────────────────────────────────────────────────────────────────────────────

import Phaser from 'phaser';
import { COLORS } from '../config';

export class BootScene extends Phaser.Scene {
  constructor() {
    super({ key: 'BootScene' });
  }

  preload(): void {
    this.load.image('tile_grass', 'assets/tiles/grass.png');
    this.load.image('tile_path', 'assets/tiles/path.png');
    this.load.image('tile_base', 'assets/tiles/base.png');
    // v0.14.0 art: tower, enemy and hero sprites (generated by scripts/generate_sprite_art.py)
    for (const n of ['arrow_t1', 'arrow_t2', 'cannon_t1', 'cannon_t2', 'magic_t1', 'magic_t2', 'slow_t1', 'slow_t2', 'acid_t1', 'watchtower',
      'grunt', 'runner', 'golem', 'wyvern', 'boss_goliath', 'hero']) {
      this.load.image(`spr_${n}`, `assets/art/${n}.png`);
    }
    // v0.12.0 art: terrain variants and interface icons (generated by scripts/generate_ui_art.py)
    for (const v of ['a', 'b', 'c', 'd']) this.load.image(`tile_grass_${v}`, `assets/tiles/grass_${v}.png`);
    for (const v of ['a', 'b', 'c']) this.load.image(`tile_path_${v}`, `assets/tiles/path_${v}.png`);
    for (const k of ['icon_heart', 'icon_gold', 'icon_lumber', 'tw_arrow', 'tw_cannon', 'tw_magic', 'tw_slow', 'tw_acid', 'tw_watchtower']) {
      this.load.image(k, `assets/ui/${k}.png`);
    }
  }

  create(): void {
    // Crisp pixels — no bilinear blur for procedural geometry

    // Warm dark background during handoff
    this.cameras.main.setBackgroundColor(COLORS.walnutDark);

    // Procedural game — nothing to load; jump straight to menu
    this.scene.start('MenuScene');
  }
}
