// Generates docs/ECONOMY_REPORT.md from the deterministic headless simulation.
//   npm run report:economy            print the report
//   npm run report:economy -- --write rewrite docs/ECONOMY_REPORT.md
// Run from the repository root. tests/economy.test.mjs fails when the committed report is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import { BUILDS, game, rankedSlots, simulate, waveTable } from '../tests/support/simulate.mjs';

const REPORT_PATH = 'docs/ECONOMY_REPORT.md';
const HEAD_START = 600;
const sum = (rows, key) => rows.reduce((total, row) => total + row[key], 0);
const table = (header, rows) => [
  `| ${header.join(' | ')} |`,
  `| ${header.map(() => '---').join(' | ')} |`,
  ...rows.map((row) => `| ${row.join(' | ')} |`),
].join('\n');

function buildRows(result) {
  return result.rows.map((row) => [
    row.wave, row.goldAtStart, row.spentBefore, row.towers, row.invested, row.kills, row.leaks,
    row.livesAtStart - row.livesLost, row.clearSecs === null ? '-' : row.clearSecs.toFixed(1),
  ]);
}
const BUILD_HEADER = ['wave', 'gold at start', 'spent before', 'towers', 'invested', 'kills', 'leaks', 'lives left', 'clear s'];

// Exhaustive wave-1 opening search over the best-covered cells (hero parked on the base).
const OPENINGS = {
  'arrow x3': ['arrow_t1', 'arrow_t1', 'arrow_t1'],
  'magic x2': ['magic_t1', 'magic_t1'],
  'arrow + magic': ['arrow_t1', 'magic_t1'],
  'arrow x2 + slow': ['arrow_t1', 'arrow_t1', 'slow_t1'],
  'magic + slow': ['magic_t1', 'slow_t1'],
  'arrow + cannon': ['arrow_t1', 'cannon_t1'],
};
// Every distinct assignment of the towers to cells: identical towers are chosen as a combination, so
// no layout is simulated twice and no layout is missed.
function searchOpening(ids, slots) {
  const groups = [...new Set(ids)].map((id) => ({ id, count: ids.filter((x) => x === id).length }));
  let best = null;
  let worst = 0;
  let runs = 0;
  const assign = (groupIndex, free, layout) => {
    if (groupIndex === groups.length) {
      const leaks = simulate({ layout, maxWave: 1, slotCap: 0 }).rows[0].leaks;
      runs++;
      worst = Math.max(worst, leaks);
      if (!best || leaks < best.leaks) best = { leaks, layout };
      return;
    }
    const { id, count } = groups[groupIndex];
    const pick = (start, chosen) => {
      if (chosen.length === count) {
        assign(groupIndex + 1, free.filter((slot) => !chosen.includes(slot)), [...layout, ...chosen.map((slot) => ({ id, col: slot.col, row: slot.row }))]);
        return;
      }
      for (let i = start; i < free.length; i++) pick(i + 1, [...chosen, free[i]]);
    };
    pick(0, []);
  };
  assign(0, slots, []);
  return { runs, best, worst };
}

export function buildReport() {
  const normal = waveTable('normal');
  const bank = simulate({ baseline: 'oracle_bank' });
  const spend = simulate({ baseline: 'oracle_spend' });
  const defaults = Object.keys(BUILDS).map((name) => simulate({ build: name }));
  const headStart = Object.keys(BUILDS).map((name) => simulate({ build: name, extraGold: HEAD_START }));
  const slots = rankedSlots().slice(0, 16);
  const openings = Object.entries(OPENINGS).map(([name, ids]) => ({ name, ...searchOpening(ids, slots) }));
  const bestOverall = Math.min(...openings.map((o) => o.best.leaks));

  const bonusTotal = (difficulty) => sum(waveTable(difficulty), 'bonus');
  const killAllIncome = sum(normal, 'income');
  const hpPerGold = (wave) => normal[wave - 1].totalHp / normal[wave - 1].income;

  const lines = [];
  lines.push('# Economy and wave-pressure report (generated)');
  lines.push('');
  lines.push('Generated by `npm run report:economy -- --write` from the headless simulation in `tests/support/simulate.mjs`.');
  lines.push('Do not edit by hand: `tests/economy.test.mjs` fails when this file is stale. Regenerate it after any change to');
  lines.push('wave, enemy, tower, difficulty or economy data. Browser smoke: not run. This report measures; it changes no balance.');
  lines.push('');
  lines.push('## Method and limits');
  lines.push('');
  lines.push('- Real `WaveManager`, `Enemy`, `Tower`, `Projectile`, `Hero`, `BuildSystem`, `EconomyManager` and `InterestSystem`');
  lines.push('  code, stepped at 30 Hz in the frame order of `GameScene.update`. No randomness: a run is reproducible bit for bit.');
  lines.push('- Towers are bought only during countdowns, through the real pointer pipeline of `BuildSystem`, on the 24 cells that');
  lines.push('  cover the most lane waypoints (see `rankedSlots`). A build is an ordered rule list; the first applicable rule is bought');
  lines.push('  when affordable, otherwise the build waits.');
  lines.push('- In this report the hero is parked on the base and only auto-attacks; the scripted Q/W rule is used in');
  lines.push('  `docs/BALANCE_PROPOSALS.md`. Hero movement, the watchtower aura and selling are NOT simulated, so results describe');
  lines.push('  tower-only play with an idle hero. A human using skills does better by an amount this report does not measure.');
  lines.push('- `oracle_bank` kills every enemy the moment it spawns and never spends (interest compounds); `oracle_spend` empties the');
  lines.push('  purse every countdown. Together they bound the income any player can receive.');
  lines.push('');
  lines.push('## Findings');
  lines.push('');
  lines.push(`1. **Opening.** Starting gold is ${game.DIFFICULTY_PRESETS.normal.startingGold}. The best of ${openings.reduce((n, o) => n + o.runs, 0)} searched opening layouts (${openings.length} tower sets on the 16 best cells)`);
  lines.push(`   leaks ${bestOverall} of ${normal[0].count} enemies in wave 1; see the opening search below.`);
  lines.push(`2. **Catalogued builds with the default economy:** ${defaults.map((r) => `${r.build} ${r.result === 'victory' ? 'wins' : `defeated in wave ${r.reachedWave}`}`).join(', ')}.`);
  lines.push(`   With +${HEAD_START} starting gold: ${headStart.map((r) => `${r.build} ${r.result === 'victory' ? 'wins' : `defeated in wave ${r.reachedWave}`}`).join(', ')}.`);
  lines.push(`3. **Income is bounded.** Killing everything pays ${killAllIncome} gold in bounties and wave bonuses over 40 waves; banking it adds`);
  lines.push(`   ${sum(bank.rows, 'interest')} gold of interest (${Math.round(100 * sum(bank.rows, 'interest') / (sum(bank.rows, 'interest') + killAllIncome))}% of everything earned when nothing is ever spent).`);
  lines.push(`4. **Pressure against income.** Enemy HP per gold of wave income is ${hpPerGold(1).toFixed(1)} in wave 1, ${hpPerGold(20).toFixed(1)} in wave 20 and ${hpPerGold(40).toFixed(1)} in wave 40;`);
  lines.push('   bounties do not scale with the wave HP multiplier.');
  lines.push(`5. **Difficulty bonus.** The wave bonus is \`round(bonusGold x waveBonusMult)\`; total bonus over 40 waves is ${bonusTotal('normal')} / ${bonusTotal('hard')} / ${bonusTotal('insane')} gold on normal / hard / insane (easy pays the normal bonus).`);
  lines.push(`6. **Lumber sink (v0.20.0).** A full run earns ${bank.lumberEnd} lumber. Licenses, builder mastery and the ultimate towers spend it (BuilderManager); the catalogued builds buy none of them, so every run here ends with its lumber unspent.`);
  lines.push('');
  lines.push('## Wave pressure and income envelope (normal)');
  lines.push('');
  lines.push('`bank gold` and `interest` come from the `oracle_bank` run (gold before the wave and interest paid when it was cleared).');
  lines.push('');
  lines.push(table(
    ['wave', 'enemy', 'count', 'total HP', 'bounty', 'bonus', 'HP per gold', 'bank gold', 'interest'],
    normal.map((w, i) => [
      w.wave, `${w.enemyType}${w.flying ? ' (air)' : ''}`, w.count, w.totalHp, w.bounty, w.bonus,
      (w.totalHp / w.income).toFixed(1), bank.rows[i].goldAtStart, bank.rows[i].interest,
    ]),
  ));
  lines.push('');
  lines.push(`Totals: bounty ${sum(normal, 'bounty')}, bonus ${sum(normal, 'bonus')}, enemy HP ${sum(normal, 'totalHp')}; oracle_spend ends with ${spend.goldEnd} gold.`);
  lines.push('');
  lines.push('## Builds with the default economy (normal)');
  for (const result of defaults) {
    lines.push('');
    lines.push(`### ${result.build}: ${result.result} at wave ${result.reachedWave}, ${result.livesLeft} lives left, ${result.towersEnd} towers`);
    lines.push('');
    lines.push(table(BUILD_HEADER, buildRows(result)));
  }
  lines.push('');
  lines.push(`## Builds with +${HEAD_START} starting gold (diagnostic, normal)`);
  for (const result of headStart) {
    lines.push('');
    lines.push(`### ${result.build}: ${result.result} at wave ${result.reachedWave}, ${result.livesLeft} lives left, ${result.towersEnd} towers`);
    lines.push('');
    lines.push(table(BUILD_HEADER, buildRows(result)));
  }
  lines.push('');
  lines.push('## Wave 1 opening search (hero parked on the base)');
  lines.push('');
  lines.push('Every combination of the listed towers on the 16 best-covered cells, each simulated through wave 1 only.');
  lines.push('');
  lines.push(table(
    ['towers', 'layouts', 'best leaks', 'worst leaks', 'best layout (col,row)'],
    openings.map((o) => [o.name, o.runs, o.best.leaks, o.worst, o.best.layout.map((l) => `${l.col},${l.row}`).join(' ')]),
  ));
  lines.push('');
  return lines.join('\n');
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const report = buildReport();
  if (process.argv.includes('--write')) {
    const existing = (() => { try { return readFileSync(REPORT_PATH, 'utf8'); } catch { return ''; } })();
    writeFileSync(REPORT_PATH, existing.includes('\r\n') ? report.replace(/\n/g, '\r\n') : report);
    process.stdout.write(`wrote ${REPORT_PATH} (${report.length} chars)\n`);
  } else {
    process.stdout.write(report);
  }
}
